"""The invariant the whole package rests on: renderers cannot run the cipher.

A picture generated from the engine's own account of what it did is honest by
construction. A picture generated by a second implementation is honest only
until the two drift. So nothing under ``render/`` and nothing in ``player.js``
may reach the step functions, the keystream generator, or the cipher.

These checks parse imports rather than grepping for strings, so a renderer
cannot slip past them with an alias.
"""

import ast
import re
from pathlib import Path

import pytest

import solitaire_lab

PACKAGE = Path(solitaire_lab.__file__).parent
RENDER_DIR = PACKAGE / "render"
WEB = PACKAGE.parent.parent / "web"

ENGINE_MODULES = {"steps", "keystream", "cipher", "keying"}
ALLOWED_FROM_STEPS = {"Phase"}


def imports_of(path: Path):
    tree = ast.parse(path.read_text())
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            yield node.module, [a.name for a in node.names]
        elif isinstance(node, ast.Import):
            for alias in node.names:
                yield alias.name, []


@pytest.mark.parametrize("path", sorted(RENDER_DIR.glob("*.py")), ids=lambda p: p.name)
def test_renderers_import_no_engine(path):
    offenders = []
    for module, names in imports_of(path):
        leaf = module.rsplit(".", 1)[-1]
        if leaf not in ENGINE_MODULES:
            continue
        if leaf == "steps" and set(names) <= ALLOWED_FROM_STEPS:
            continue
        offenders.append((module, names))
    assert not offenders, f"{path.name} reaches into the engine: {offenders}"


def test_renderers_never_call_step_functions():
    """Even a lazily-imported step call inside a function body is out."""
    banned = {
        "move_joker_a",
        "move_joker_b",
        "move_joker_down",
        "triple_cut",
        "count_cut",
        "output_card",
        "generate",
    }
    for path in RENDER_DIR.glob("*.py"):
        tree = ast.parse(path.read_text())
        calls = {
            n.func.id
            for n in ast.walk(tree)
            if isinstance(n, ast.Call) and isinstance(n.func, ast.Name) and n.func.id in banned
        }
        assert not calls, f"{path.name} calls engine functions: {calls}"


def test_player_js_knows_nothing_about_the_cipher():
    """The browser player draws cards. It must not value them, move them, or phrase them."""
    raw = (WEB / "player.js").read_text()
    source = re.sub(r"/\*.*?\*/|//[^\n]*", "", raw, flags=re.S)  # comments may describe; code may not
    for forbidden in [
        "SUIT_OFFSET",
        "cardValue",
        "valueLetter",
        "function explain",  # values and wording
        "tripleCut",
        "countCut",
        "moveJoker",
        "encrypt",
        "keystream(",  # the cipher itself
    ]:
        assert forbidden not in source, f"player.js must not contain {forbidden!r}"


def test_trace_schema_stays_free_of_prose():
    """Wording ships in a sidecar generated by the renderer, never in events."""
    from solitaire_lab.deck import ORDERED_DECK
    from solitaire_lab.keystream import generate
    from solitaire_lab.trace.schema import to_dict

    trace = to_dict(generate(ORDERED_DECK, 3, trace=True).trace)
    for event in trace["events"]:
        assert set(event) <= {"round", "phase", "after", "affected", "meta", "output"}
        assert not any(isinstance(v, str) and len(v) > 40 for v in event["meta"].values())
